    tmp_scale = tmp12 * tl.math.rsqrt(tmp3 + 1e-05)
    # Step 2: adjusted bias = bias - mean * scale  --> FFMA(-mean, scale, bias)
    tmp_bias_adj = tmp14 - tmp1 * tmp_scale
    # Step 3: output = x * scale + bias_adj  --> FFMA(x, scale, bias_adj)
    tmp_out = tmp0 * tmp_scale + tmp_bias_adj
    # Hardtanh [0, 6] via tl.where (predicated select, avoids FMAX+FMIN pair)
    tmp_clamp = tl.where(tmp_out < 0.0, 0.0, tl.where(tmp_out > 6.0, 6.0, tmp_out))
    tl.store(in_out_ptr0 + (x2), tmp_clamp, xmask)

