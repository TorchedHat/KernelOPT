# Fused BatchNorm + ReLU kernel
@triton.autotune(
    configs=[
        triton.Config({'BLOCK_SIZE': 1024}, num_warps=8),
        triton.Config({'BLOCK_SIZE': 512}, num_warps=4),
        triton.Config({'BLOCK_SIZE': 256}, num_warps=4),
        triton.Config({'BLOCK_SIZE': 128}, num_warps=2),
    ],
    key=['n_channels', 'spatial'],
)
@triton.jit
def fused_bn_relu_kernel(
    x_ptr, out_ptr,
    mean_ptr, var_ptr, weight_ptr, bias_ptr,
    n_channels, spatial, eps,
    BLOCK_SIZE: tl.constexpr,
):
    pid = tl.program_id(0)
    # Each program handles BLOCK_SIZE elements
    offsets = pid * BLOCK_SIZE + tl.arange(0, BLOCK_SIZE)
    total = n_channels * spatial
    mask = offsets < total
    
    # Compute channel index
    c = (offsets // spatial) % n_channels
    
    x = tl.load(x_ptr + offsets, mask=mask, other=0.0)
    mean = tl.load(mean_ptr + c, mask=mask, other=0.0)
    var = tl.load(var_ptr + c, mask=mask, other=1.0)
    w = tl.load(weight_ptr + c, mask=mask, other=1.0)
    b = tl.load(bias_ptr + c, mask=mask, other=0.0)
    
    # BN: (x - mean) / sqrt(var + eps) * weight + bias
    x_norm = (x - mean) / tl.sqrt(var + eps)
    out = x_norm * w + b
    # ReLU
    out = tl.maximum(out, 0.0)
    
    tl.store(out_ptr + offsets, out, mask=mask)


def fused_bn_relu(x, weight, bias, running_mean, running_var, eps=1e-5):
    """Apply batch norm (inference mode) + ReLU"""
    N, C, H, W = x.shape
    spatial = H * W
    # x is in NCHW format, we need to handle indexing
    # Flatten to (N*H*W, C) style but keep NCHW layout
    # Actually x is contiguous NCHW: index = n*C*H*W + c*H*W + h*W + w
    # channel = (flat_idx // (H*W)) % C  -- but flat_idx goes over N*C*H*W
    # Let's reshape to (N*C, H*W) and process
    x_flat = x.reshape(N * C, H * W)
    out_flat = torch.empty_like(x_flat)
    
    total = N * C * H * W
    # We need channel index: for flat index i in N*C*H*W, channel = (i // (H*W)) % C
    # But in our kernel, we process flat over n_channels * spatial where n_channels = N*C? No.
    # Let's think differently: process as (N, C, H*W) and map channel = c
    # Reshape x to (N, C, H*W), process each element with channel c
    
    # Actually simpler: process flat array of size N*C*H*W
    # channel index = (flat_idx // (H*W)) % C
    # But our kernel uses (offsets // spatial) % n_channels
    # If we set spatial = H*W and n_channels = C, but we have N batches...
    # We need to handle batch: flat_idx in [0, N*C*H*W)
    # channel = (flat_idx // (H*W)) % C
    # This works if we set spatial = H*W and treat the full tensor as n_channels*spatial
    # but n_channels here should be C and we need to handle N
    
    # Let's just use a different approach: reshape to (N*C, H*W)
    # and use a kernel where channel = pid_channel
    # Actually the simplest: use the flat kernel with n_channels=C, spatial=N*H*W
    # but then channel index = (flat_idx // (N*H*W)) % C -- wrong order
    
    # NCHW: flat_idx = n*C*H*W + c*H*W + h*W + w
    # channel c = (flat_idx // (H*W)) % C
    # So spatial_per_channel = H*W, and we have N*C channels total? No.
    # Let's use: for flat_idx in [0, N*C*H*W):
    #   c = (flat_idx // (H*W)) % C
    # This means: spatial = H*W, and we iterate over N*C "channel slots"
    # But our kernel does: c = (offsets // spatial) % n_channels
    # If spatial = H*W and n_channels = C:
    #   c = (flat_idx // (H*W)) % C -- correct!
    # But flat_idx goes from 0 to N*C*H*W, so we need total = N*C*H*W
    
    x_contig = x.contiguous()
    out = torch.empty_like(x_contig)
    
    total_elements = N * C * H * W
    BLOCK_SIZE = 1024
    grid = lambda meta: ((total_elements + meta['BLOCK_SIZE'] - 1) // meta['BLOCK_SIZE'],)
    
    fused_bn_relu_kernel[grid](
        x_contig, out,
        running_mean, running_var, weight, bias,
        C, H * W, eps,
    )
    return out


