# Fused BatchNorm + ReLU kernel
@triton.autotune(
    configs=[
        triton.Config({'BLOCK_SIZE': 1024}, num_warps=4),
        triton.Config({'BLOCK_SIZE': 2048}, num_warps=8),
        triton.Config({'BLOCK_SIZE': 512}, num_warps=4),
        triton.Config({'BLOCK_SIZE': 256}, num_warps=4),
    ],
    key=['n_channels', 'spatial'],
)
@triton.jit
def bn_relu_kernel(
    x_ptr, out_ptr,
    mean_ptr, var_ptr, weight_ptr, bias_ptr,
    n_channels, spatial,
    eps: tl.constexpr,
    BLOCK_SIZE: tl.constexpr,
):
    # Each program handles BLOCK_SIZE elements
    # Layout: (N, C, H, W) -> flat index, channel = (idx // spatial) % n_channels
    pid = tl.program_id(0)
    offsets = pid * BLOCK_SIZE + tl.arange(0, BLOCK_SIZE)
    total = n_channels * spatial
    # We process across all N*C*H*W elements
    # But we need channel index for BN params
    # Actually let's do per-channel: pid = channel, loop over spatial*N
    # Better: flat indexing where channel = (flat_idx // spatial) % n_channels
    mask = offsets < total * (spatial // spatial)  # placeholder
    # This approach is complex; use 2D grid instead
    pass


# Better approach: 2D kernel where dim0=channel, dim1=spatial*batch
@triton.autotune(
    configs=[
        triton.Config({'BLOCK_N': 1024}, num_warps=4),
        triton.Config({'BLOCK_N': 2048}, num_warps=8),
        triton.Config({'BLOCK_N': 512}, num_warps=4),
        triton.Config({'BLOCK_N': 256}, num_warps=4),
    ],
    key=['total_elements'],
)
@triton.jit
def fused_bn_relu_flat_kernel(
    x_ptr, out_ptr,
    mean_ptr, var_ptr, weight_ptr, bias_ptr,
    total_elements, n_channels, hw,
    eps: tl.constexpr,
    BLOCK_N: tl.constexpr,
):
    pid = tl.program_id(0)
    offsets = pid * BLOCK_N + tl.arange(0, BLOCK_N)
    mask = offsets < total_elements
    
    # channel index: (offset // hw) % n_channels
    chan = (offsets // hw) % n_channels
    
    x = tl.load(x_ptr + offsets, mask=mask, other=0.0).to(tl.float32)
    mean = tl.load(mean_ptr + chan, mask=mask, other=0.0).to(tl.float32)
    var = tl.load(var_ptr + chan, mask=mask, other=0.0).to(tl.float32)
    w = tl.load(weight_ptr + chan, mask=mask, other=1.0).to(tl.float32)
    b = tl.load(bias_ptr + chan, mask=mask, other=0.0).to(tl.float32)
    
    x_norm = (x - mean) / tl.sqrt(var + eps)
    out = x_norm * w + b
    out = tl.maximum(out, 0.0)
    
    tl.store(out_ptr + offsets, out.to(tl.float32), mask=mask)


def fused_bn_relu(x, mean, var, weight, bias, eps=1e-5):
    N, C, H, W = x.shape
    out = torch.empty_like(x)
    total = N * C * H * W
    hw = H * W
    grid = lambda meta: (triton.cdiv(total, meta['BLOCK_N']),)
    fused_bn_relu_flat_kernel[grid](
        x, out, mean, var, weight, bias,
    )
    return out


