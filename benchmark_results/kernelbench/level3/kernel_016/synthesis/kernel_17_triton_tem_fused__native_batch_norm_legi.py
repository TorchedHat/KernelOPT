import torch
import triton
import triton.language as tl
import torch.nn.functional as F

@triton.autotune(
    configs=[
        triton.Config({'BLOCK_SIZE': 1024}, num_warps=4),
        triton.Config({'BLOCK_SIZE': 512}, num_warps=4),
        triton.Config({'BLOCK_SIZE': 256}, num_warps=4),
        triton.Config({'BLOCK_SIZE': 128}, num_warps=2),
    ],
    key=['numel', 'num_channels'],
)
@triton.jit
def fused_bn_relu_kernel(
    x_ptr, mean_ptr, var_ptr, weight_ptr, bias_ptr,
    out_ptr,
    numel, num_channels, spatial,
    eps: tl.constexpr,
    BLOCK_SIZE: tl.constexpr,
):
    pid = tl.program_id(0)
    offsets = pid * BLOCK_SIZE + tl.arange(0, BLOCK_SIZE)
    mask = offsets < numel
    
    x = tl.load(x_ptr + offsets, mask=mask, other=0.0)
    c = (offsets // spatial) % num_channels
    
    mean = tl.load(mean_ptr + c, mask=mask, other=0.0)
    var = tl.load(var_ptr + c, mask=mask, other=1.0)
    w = tl.load(weight_ptr + c, mask=mask, other=1.0)
    b = tl.load(bias_ptr + c, mask=mask, other=0.0)
    
    x_norm = (x - mean) / tl.sqrt(var + eps)
    out = x_norm * w + b
    out = tl.maximum(out, 0.0)
    
    tl.store(out_ptr + offsets, out, mask=mask)


def bn_relu(x, weight, bias, running_mean, running_var, eps=1e-5):
    N, C, H, W = x.shape
    out = torch.empty_like(x)
    numel = x.numel()
    spatial = H * W
    
    # Reshape to NHWC-like for channel indexing: need (N*H*W, C) or flat with channel stride
    # x is NCHW: index = n*C*H*W + c*H*W + h*W + w
    # channel = (index // (H*W)) % C
    
    grid = lambda meta: (triton.cdiv(numel, meta['BLOCK_SIZE']),)
    fused_bn_relu_kernel[grid](
        x, running_mean, running_var, weight, bias,
        out,
        numel, C, H * W,
        eps,
    )
    return out


def conv2d_bn_relu(x, conv_weight, bn_weight, bn_bias, bn_mean, bn_var, 
                   stride=1, padding=0, eps=1e-5):
    x = F.conv2d(x, conv_weight, bias=None, stride=stride, padding=padding)
    x = bn_relu(x, bn_weight, bn_bias, bn_mean, bn_var, eps)
    return x


def dense_layer(x, bn_weight, bn_bias, bn_mean, bn_var, conv_weight, eps=1e-5):
    # BN + ReLU + Conv + Dropout(0.0) = identity dropout
    x_bn = bn_relu(x, bn_weight, bn_bias, bn_mean, bn_var, eps)
    x_conv = F.conv2d(x_bn, conv_weight, bias=None, stride=1, padding=1)
    return x_conv


def transition_layer(x, bn_weight, bn_bias, bn_mean, bn_var, conv_weight, eps=1e-5):
    x_bn = bn_relu(x, bn_weight, bn_bias, bn_mean, bn_var, eps)
    x_conv = F.conv2d(x_bn, conv_weight, bias=None, stride=1, padding=0)
    x_pool = F.avg_pool2d(x_conv, kernel_size=2, stride=2)
    return x_pool


