    out = x_norm * w + b
    # HardTanh (clamp to [-6, 6] for ReLU6)
    out = tl.where(out < -6.0, -6.0, out)
    out = tl.where(out > 6.0, 6.0, out)
    
    tl.store(out_ptr + offsets, out.to(tl.float32), mask=mask)


