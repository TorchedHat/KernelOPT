def triton_conv2d(x, weight, bias, stride=(1,1), padding=(0,0), apply_relu=False):
    N, IN_C, IN_H, IN_W = x.shape
    OUT_C, _, KH, KW = weight.shape
    SH, SW = stride
    PH, PW = padding

    OUT_H = (IN_H + 2*PH - KH) // SH + 1
    OUT_W = (IN_W + 2*PW - KW) // SW + 1

    M = N * OUT_H * OUT_W
    K = IN_C * KH * KW

    y = torch.empty((N, OUT_C, OUT_H, OUT_W), device=x.device, dtype=x.dtype)

    grid = lambda meta: (
        triton.cdiv(M, meta['BLOCK_M']),
        triton.cdiv(OUT_C, meta['BLOCK_N']),
    )

    has_bias = bias is not None

    conv2d_implicit_gemm_kernel[grid](
        y,
        N, IN_C, IN_H, IN_W,
        OUT_C, OUT_H, OUT_W,
        KH, KW,
        SH, SW,
        PH, PW,
        M, OUT_C, K,
        x.stride(0), x.stride(1), x.stride(2), x.stride(3),
        weight.stride(0), weight.stride(1), weight.stride(2), weight.stride(3),
        y.stride(0), y.stride(1), y.stride(2), y.stride(3),
        HAS_BIAS=has_bias,
        APPLY_RELU=apply_relu,
    )
    return y


def triton_relu(x):
    y = torch.empty_like(x)
    N = x.numel()
    grid = lambda meta: (triton.cdiv(N, meta['BLOCK_SIZE']),)
    relu_kernel[grid](x, y, N)
    return y


def triton_max_pool2d(x, kernel_size=3, stride=2, padding=1):
    N, C, IN_H, IN_W = x.shape
    KH = KW = kernel_size
    SH = SW = stride
    PH = PW = padding

    OUT_H = (IN_H + 2*PH - KH) // SH + 1
    OUT_W = (IN_W + 2*PW - KW) // SW + 1

    y = torch.empty((N, C, OUT_H, OUT_W), device=x.device, dtype=x.dtype)
    N_total = N * C * OUT_H * OUT_W

    grid = lambda meta: (triton.cdiv(N_total, meta['BLOCK_SIZE']),)
    max_pool2d_kernel[grid](
        x, y,
        N, C, IN_H, IN_W,
        OUT_H, OUT_W,
        KH, KW,
        SH, SW,
        PH, PW,
        N_total,
    )
    return y


def triton_max_pool2d_s1(x, kernel_size=3, stride=1, padding=1):
    return triton_max_pool2d(x, kernel_size=kernel_size, stride=stride, padding=padding)


def triton_adaptive_avg_pool2d(x, output_size=(1,1)):
    N, C, IN_H, IN_W = x.shape
    OUT_H, OUT_W = output_size
    y = torch.empty((N, C, OUT_H, OUT_W), device=x.device, dtype=x.dtype)
    N_total = N * C * OUT_H * OUT_W

    grid = lambda meta: (triton.cdiv(N_total, meta['BLOCK_SIZE']),)
    adaptive_avg_pool2d_kernel[grid](
        x, y,
        N, C, IN_H, IN_W,
        OUT_H, OUT_W,
        N_total,
    )
    return y


def triton_linear(x, weight, bias):
    # x: (M, K), weight: (N, K), bias: (N,)
    M, K = x.shape
    N = weight.shape[0]
    y = torch.empty((M, N), device=x.device, dtype=x.dtype)

    grid = lambda meta: (
        triton.cdiv(M, meta['BLOCK_M']),
        triton.cdiv(N, meta['BLOCK_N']),
    )

    has_bias = bias is not None
    linear_kernel[grid](
        x, weight, bias if has_bias else x,
        y,
        M, N, K,
        x.stride(0), x.stride(1),
        weight.stride(0), weight.stride(1),
        y.stride(0), y.stride(1),
        HAS_BIAS=has_bias,
    )
    return y


