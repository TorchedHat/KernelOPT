# Fused BatchNorm (inference) + ReLU kernel
@triton.autotune(
    configs=[
        triton.Config({'BLOCK_SIZE': 1024}, num_warps=4),
        triton.Config({'BLOCK_SIZE': 512}, num_warps=4),
        triton.Config({'BLOCK_SIZE': 256}, num_warps=4),
        triton.Config({'BLOCK_SIZE': 128}, num_warps=4),
    ],
    key=['numel', 'num_channels'],
)
@triton.jit
def fused_bn_relu_kernel(
    x_ptr, out_ptr,
    mean_ptr, var_ptr, weight_ptr, bias_ptr,
    numel, num_channels, spatial,
    eps,
    BLOCK_SIZE: tl.constexpr,
):
    pid = tl.program_id(0)
    offsets = pid * BLOCK_SIZE + tl.arange(0, BLOCK_SIZE)
    mask = offsets < numel

    # Compute channel index for each element
    # Layout: (N, C, H, W) -> channel = (offset / spatial) % num_channels
    chan = (offsets // spatial) % num_channels

    x = tl.load(x_ptr + offsets, mask=mask, other=0.0)
    mean = tl.load(mean_ptr + chan, mask=mask, other=0.0)
    var = tl.load(var_ptr + chan, mask=mask, other=1.0)
    weight = tl.load(weight_ptr + chan, mask=mask, other=1.0)
    bias = tl.load(bias_ptr + chan, mask=mask, other=0.0)

    # BN: (x - mean) / sqrt(var + eps) * weight + bias
    inv_std = 1.0 / tl.sqrt(var + eps)
    x_norm = (x - mean) * inv_std * weight + bias

    # ReLU
    out = tl.maximum(x_norm, 0.0)
    tl.store(out_ptr + offsets, out, mask=mask)


def fused_bn_relu(x, weight, bias, running_mean, running_var, eps=1e-5):
    N, C, H, W = x.shape
    numel = N * C * H * W
    spatial = H * W
    out = torch.empty_like(x)
    grid = lambda meta: (triton.cdiv(numel, meta['BLOCK_SIZE']),)
    fused_bn_relu_kernel[grid](
        x, out,
        running_mean, running_var, weight, bias,
        numel, C, spatial,
        eps,
    )
    return out


def conv2d(x, weight, bias=None, stride=1, padding=0):
    return torch.nn.functional.conv2d(x, weight, bias, stride, padding)


def dense_layer_forward(x, bn_weight, bn_bias, bn_mean, bn_var, conv_weight):
    """BN + ReLU + Conv2d + (dropout with p=0, so identity)"""
    out = fused_bn_relu(x, bn_weight, bn_bias, bn_mean, bn_var)
    out = torch.nn.functional.conv2d(out, conv_weight, None, 1, 1)
    # dropout with p=0.0 is identity
    return out


def transition_forward(x, bn_weight, bn_bias, bn_mean, bn_var, conv_weight):
    """BN + ReLU + Conv2d(1x1) + AvgPool2d"""
    out = fused_bn_relu(x, bn_weight, bn_bias, bn_mean, bn_var)
    out = torch.nn.functional.conv2d(out, conv_weight, None, 1, 0)
    out = torch.nn.functional.avg_pool2d(out, kernel_size=2, stride=2)
    return out


