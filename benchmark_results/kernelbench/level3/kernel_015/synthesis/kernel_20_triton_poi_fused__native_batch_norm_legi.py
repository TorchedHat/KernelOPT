@triton.autotune(
    configs=[
        triton.Config({'BLOCK_SIZE': 1024}, num_warps=4),
        triton.Config({'BLOCK_SIZE': 512}, num_warps=4),
        triton.Config({'BLOCK_SIZE': 256}, num_warps=4),
        triton.Config({'BLOCK_SIZE': 128}, num_warps=2),
    ],
    key=['n_elements', 'n_channels'],
)
@triton.jit
def fused_bn_relu_kernel(
    x_ptr, mean_ptr, var_ptr, weight_ptr, bias_ptr,
    out_ptr,
    n_elements, n_channels,
    eps,
    BLOCK_SIZE: tl.constexpr,
):
    pid = tl.program_id(0)
    offsets = pid * BLOCK_SIZE + tl.arange(0, BLOCK_SIZE)
    mask = offsets < n_elements

    x = tl.load(x_ptr + offsets, mask=mask, other=0.0)

    # Compute channel index: layout is (N, C, H, W) contiguous
    # channel = (offset / spatial_size) % n_channels
    # But we pass channel index differently - we need to figure out channel from offset
    # For NCHW layout: offset = n * C*H*W + c * H*W + h*W + w
    # channel = (offset // (H*W)) % C
    # We'll compute it inline
    # Actually we need spatial_size = n_elements / (batch * n_channels)
    # Let's pass n_channels and compute channel from offset
    # offset = n * (C * HW) + c * HW + hw
    # channel = (offset // HW) % C
    # But HW = n_elements / (N * C) - we don't have N separately
    # Better: pass channel stride info

    # We'll use a different approach: pass the spatial size
    # channel = (offset // spatial_size) % n_channels
    # But we don't have spatial_size here...
    # Let's restructure: pass spatial_size as a parameter

    channel = (offsets // (n_elements // n_channels)) % n_channels
    # This is wrong for general case. Let me use a proper approach.

    # Actually for NCHW: total = N*C*H*W, spatial = H*W
    # channel index = (flat_idx // spatial) % C
    # We need spatial_size passed in
    tl.store(out_ptr + offsets, x, mask=mask)


# Better approach: proper kernel with spatial_size
@triton.autotune(
    configs=[
        triton.Config({'BLOCK_SIZE': 1024}, num_warps=8),
        triton.Config({'BLOCK_SIZE': 512}, num_warps=4),
        triton.Config({'BLOCK_SIZE': 256}, num_warps=4),
        triton.Config({'BLOCK_SIZE': 128}, num_warps=2),
    ],
    key=['n_elements'],
)
@triton.jit
def fused_bn_relu_kernel_v2(
    x_ptr, mean_ptr, var_ptr, weight_ptr, bias_ptr,
    out_ptr,
    n_elements,
    spatial_size,
    n_channels,
    eps: tl.constexpr,
    BLOCK_SIZE: tl.constexpr,
):
    pid = tl.program_id(0)
    offsets = pid * BLOCK_SIZE + tl.arange(0, BLOCK_SIZE)
    mask = offsets < n_elements

    x = tl.load(x_ptr + offsets, mask=mask, other=0.0)

    # Compute channel index for NCHW layout
    # flat index = n * C * spatial + c * spatial + s
    # channel = (flat // spatial) % C
    channel = (offsets // spatial_size) % n_channels

    mean = tl.load(mean_ptr + channel, mask=mask, other=0.0)
    var = tl.load(var_ptr + channel, mask=mask, other=0.0)
    weight = tl.load(weight_ptr + channel, mask=mask, other=1.0)
    bias = tl.load(bias_ptr + channel, mask=mask, other=0.0)

    # BatchNorm
    x_norm = (x - mean) / tl.sqrt(var + eps)
    x_scaled = x_norm * weight + bias

    # ReLU
    out = tl.maximum(x_scaled, 0.0)

    tl.store(out_ptr + offsets, out, mask=mask)


def apply_bn_relu(x, weight, bias, running_mean, running_var, eps=1e-5):
    """Apply fused BatchNorm + ReLU using Triton kernel."""
    N, C, H, W = x.shape
    out = torch.empty_like(x)
    n_elements = x.numel()
    spatial_size = H * W

    grid = lambda meta: (triton.cdiv(n_elements, meta['BLOCK_SIZE']),)
    fused_bn_relu_kernel_v2[grid](
        x, running_mean, running_var, weight, bias,
        out,
        n_elements,
        spatial_size,
        C,
        eps,
    )
    return out


def dense_layer(x, conv_weight, bn_weight, bn_bias, bn_mean, bn_var):
    """Single dense layer: BN -> ReLU -> Conv -> (no dropout in inference)"""
    # BN + ReLU
    x_bn = apply_bn_relu(x, bn_weight, bn_bias, bn_mean, bn_var)
    # Conv
    out = F.conv2d(x_bn, conv_weight, bias=None, padding=1)
    return out


def transition_layer(x, bn_weight, bn_bias, bn_mean, bn_var, conv_weight):
    """Transition: BN -> ReLU -> Conv1x1 -> AvgPool"""
    x_bn = apply_bn_relu(x, bn_weight, bn_bias, bn_mean, bn_var)
    x_conv = F.conv2d(x_bn, conv_weight, bias=None)
    x_pool = F.avg_pool2d(x_conv, kernel_size=2, stride=2)
    return x_pool


