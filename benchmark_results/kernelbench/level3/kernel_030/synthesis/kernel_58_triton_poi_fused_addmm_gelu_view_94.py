# Swin Transformer V2 implementation using Triton kernels
# ============================================================

def window_partition(x, window_size):
    B, H, W, C = x.shape
    x = x.view(B, H // window_size, window_size, W // window_size, window_size, C)
    windows = x.permute(0, 1, 3, 2, 4, 5).contiguous().view(-1, window_size, window_size, C)
    return windows


def window_reverse(windows, window_size, H, W):
    B = int(windows.shape[0] / (H * W / window_size / window_size))
    x = windows.view(B, H // window_size, W // window_size, window_size, window_size, -1)
    x = x.permute(0, 1, 3, 2, 4, 5).contiguous().view(B, H, W, -1)
    return x


def swin_window_attention(
    x, qkv_weight, q_bias, v_bias,
    logit_scale, proj_weight, proj_bias,
    cpb_mlp_0_weight, cpb_mlp_0_bias, cpb_mlp_2_weight,
    relative_coords_table, relative_position_index,
    num_heads, window_size, attn_mask=None
):
    B_, N, C = x.shape
    head_dim = C // num_heads

    # Build qkv bias
    qkv_bias = torch.cat([q_bias, torch.zeros_like(v_bias), v_bias])

    # QKV projection
    qkv = F.linear(x, qkv_weight, qkv_bias)
    qkv = qkv.reshape(B_, N, 3, num_heads, head_dim).permute(2, 0, 1, 3, 4)
    # Wait, reshape is (B_, N, 3, num_heads, head_dim) -> permute (2, 0, 3, 1, 4)
    qkv = qkv.reshape(B_, N, 3, num_heads, head_dim).permute(2, 0, 3, 1, 4)
    q, k, v = qkv.unbind(0)

    # Cosine attention
    q_norm = F.normalize(q, dim=-1)
    k_norm = F.normalize(k, dim=-1)

    # logit scale
    logit_scale_val = torch.clamp(logit_scale, max=torch.log(torch.tensor(1.0 / 0.01, device=logit_scale.device))).exp()
    attn = torch.matmul(q_norm, k_norm.transpose(-2, -1)) * logit_scale_val

    # Relative position bias via CPB MLP
    # cpb_mlp: Linear(2, 512) -> ReLU -> Linear(512, num_heads)
    rel_pos_bias_table = F.linear(relative_coords_table, cpb_mlp_0_weight, cpb_mlp_0_bias)
    rel_pos_bias_table = F.relu(rel_pos_bias_table)
    rel_pos_bias_table = F.linear(rel_pos_bias_table, cpb_mlp_2_weight)
    rel_pos_bias_table = rel_pos_bias_table.view(-1, num_heads)

    # Index into table
    relative_position_index_flat = relative_position_index.view(-1)
    relative_position_bias = rel_pos_bias_table[relative_position_index_flat]
    relative_position_bias = relative_position_bias.view(window_size * window_size, window_size * window_size, num_heads)
    relative_position_bias = relative_position_bias.permute(2, 0, 1).contiguous()
    relative_position_bias = torch.sigmoid(relative_position_bias) * 16
    attn = attn + relative_position_bias.unsqueeze(0)

    if attn_mask is not None:
        nW = attn_mask.shape[0]
        attn = attn.view(B_ // nW, nW, num_heads, N, N) + attn_mask.unsqueeze(1).unsqueeze(0)
        attn = attn.view(-1, num_heads, N, N)

    attn = triton_softmax(attn)

    x = torch.matmul(attn, v)
    x = x.transpose(1, 2).reshape(B_, N, C)
    x = F.linear(x, proj_weight, proj_bias)
    return x


def swin_block(
    x, H, W, window_size, shift_size, num_heads,
    norm1_w, norm1_b,
    q_bias, v_bias, qkv_weight, logit_scale,
    cpb_mlp_0_w, cpb_mlp_0_b, cpb_mlp_2_w,
    proj_w, proj_b,
    relative_coords_table, relative_position_index,
    norm2_w, norm2_b,
    mlp_fc1_w, mlp_fc1_b, mlp_fc2_w, mlp_fc2_b,
    attn_mask=None
):
    B, L, C = x.shape
    shortcut = x

    # Norm1
    x = triton_layernorm(x, norm1_w, norm1_b)
    x = x.view(B, H, W, C)

    # Cyclic shift
    if shift_size > 0:
        shifted_x = torch.roll(x, shifts=(-shift_size, -shift_size), dims=(1, 2))
    else:
        shifted_x = x

    # Window partition
    x_windows = window_partition(shifted_x, window_size)
    x_windows = x_windows.view(-1, window_size * window_size, C)

    # Attention
    attn_windows = swin_window_attention(
        x_windows, qkv_weight, q_bias, v_bias,
        logit_scale, proj_w, proj_b,
        cpb_mlp_0_w, cpb_mlp_0_b, cpb_mlp_2_w,
        relative_coords_table, relative_position_index,
    )

    # Reverse window
    attn_windows = attn_windows.view(-1, window_size, window_size, C)
    shifted_x = window_reverse(attn_windows, window_size, H, W)

    # Reverse cyclic shift
    if shift_size > 0:
        x = torch.roll(shifted_x, shifts=(shift_size, shift_size), dims=(1, 2))
    else:
        x = shifted_x

    x = x.view(B, H * W, C)
    x = shortcut + x

    # MLP
    shortcut2 = x
    x = triton_layernorm(x, norm2_w, norm2_b)
    x = F.linear(x, mlp_fc1_w, mlp_fc1_b)
    x = triton_gelu(x)
    x = F.linear(x, mlp_fc2_w, mlp_fc2_b)
    x = shortcut2 + x

    return x


def patch_merging(x, H, W, reduction_w, norm_w, norm_b):
    B, L, C = x.shape
    x = x.view(B, H, W, C)

    x0 = x[:, 0::2, 0::2, :]
    x1 = x[:, 1::2, 0::2, :]
    x2 = x[:, 0::2, 1::2, :]
    x3 = x[:, 1::2, 1::2, :]
    x = torch.cat([x0, x1, x2, x3], dim=-1)
    x = x.view(B, -1, 4 * C)

    x = F.linear(x, reduction_w)
    x = triton_layernorm(x, norm_w, norm_b)
    return x


