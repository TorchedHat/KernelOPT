import torch
import triton
import triton.language as tl
from triton.language.extra import libdevice

@triton.autotune(
    configs=[
        triton.Config({'BLOCK_SIZE': 64}, num_warps=2),
        triton.Config({'BLOCK_SIZE': 128}, num_warps=4),
        triton.Config({'BLOCK_SIZE': 256}, num_warps=8),
        triton.Config({'BLOCK_SIZE': 512}, num_warps=8),
    ],
    key=['N'],
)
@triton.jit
def layer_norm_kernel(
    x_ptr, weight_ptr, bias_ptr, out_ptr,
    M, N, eps,
    stride_m,
    BLOCK_SIZE: tl.constexpr,
):
    row = tl.program_id(0)
    x_ptr = x_ptr + row * stride_m
    out_ptr = out_ptr + row * stride_m

    mean = tl.zeros((), dtype=tl.float32)
    var = tl.zeros((), dtype=tl.float32)

    # Compute mean
    for off in range(0, N, BLOCK_SIZE):
        cols = off + tl.arange(0, BLOCK_SIZE)
        mask = cols < N
        x = tl.load(x_ptr + cols, mask=mask, other=0.0).to(tl.float32)
        mean += tl.sum(x, axis=0)
    mean = mean / N

    # Compute variance
    for off in range(0, N, BLOCK_SIZE):
        cols = off + tl.arange(0, BLOCK_SIZE)
        mask = cols < N
        x = tl.load(x_ptr + cols, mask=mask, other=0.0).to(tl.float32)
        diff = tl.where(mask, x - mean, 0.0)
        var += tl.sum(diff * diff, axis=0)
    var = var / N
    rstd = 1.0 / libdevice.sqrt(var + eps)

    # Normalize and apply weight/bias
    for off in range(0, N, BLOCK_SIZE):
        cols = off + tl.arange(0, BLOCK_SIZE)
        mask = cols < N
        x = tl.load(x_ptr + cols, mask=mask, other=0.0).to(tl.float32)
        w = tl.load(weight_ptr + cols, mask=mask, other=1.0).to(tl.float32)
        b = tl.load(bias_ptr + cols, mask=mask, other=0.0).to(tl.float32)
        y = (x - mean) * rstd * w + b
        tl.store(out_ptr + cols, y.to(tl.float32), mask=mask)


@triton.autotune(
    configs=[
        triton.Config({'BLOCK_SIZE': 64}, num_warps=2),
        triton.Config({'BLOCK_SIZE': 128}, num_warps=4),
        triton.Config({'BLOCK_SIZE': 256}, num_warps=8),
        triton.Config({'BLOCK_SIZE': 512}, num_warps=8),
    ],
    key=['N'],
)
@triton.jit
def softmax_kernel(
    out_ptr, in_ptr,
    M, N,
    stride_m,
    BLOCK_SIZE: tl.constexpr,
):
    row = tl.program_id(0)
    in_ptr = in_ptr + row * stride_m
    out_ptr = out_ptr + row * stride_m

    # Find max
    row_max = tl.full((), float('-inf'), dtype=tl.float32)
    for off in range(0, N, BLOCK_SIZE):
        cols = off + tl.arange(0, BLOCK_SIZE)
        mask = cols < N
        x = tl.load(in_ptr + cols, mask=mask, other=float('-inf')).to(tl.float32)
        row_max = tl.maximum(row_max, tl.max(x, axis=0))

    # Compute sum of exp
    row_sum = tl.zeros((), dtype=tl.float32)
    for off in range(0, N, BLOCK_SIZE):
        cols = off + tl.arange(0, BLOCK_SIZE)
        mask = cols < N
        x = tl.load(in_ptr + cols, mask=mask, other=float('-inf')).to(tl.float32)
        row_sum += tl.sum(tl.exp(x - row_max), axis=0)

    # Store normalized
    for off in range(0, N, BLOCK_SIZE):
        cols = off + tl.arange(0, BLOCK_SIZE)
        mask = cols < N
        x = tl.load(in_ptr + cols, mask=mask, other=float('-inf')).to(tl.float32)
        y = tl.exp(x - row_max) / row_sum
        tl.store(out_ptr + cols, y.to(tl.float32), mask=mask)


@triton.autotune(
    configs=[
        triton.Config({'BLOCK_SIZE': 256}, num_warps=4),
        triton.Config({'BLOCK_SIZE': 512}, num_warps=8),
        triton.Config({'BLOCK_SIZE': 1024}, num_warps=8),
        triton.Config({'BLOCK_SIZE': 2048}, num_warps=16),
    ],
    key=['N'],
)
@triton.jit
def gelu_kernel(
    out_ptr, in_ptr,
    N,
    BLOCK_SIZE: tl.constexpr,
):
    pid = tl.program_id(0)
    offs = pid * BLOCK_SIZE + tl.arange(0, BLOCK_SIZE)
    mask = offs < N
    x = tl.load(in_ptr + offs, mask=mask, other=0.0).to(tl.float32)
    # GELU: x * 0.5 * (1 + tanh(sqrt(2/pi) * (x + 0.044715 * x^3)))
    cdf = 0.5 * (1.0 + libdevice.tanh(0.7978845608028654 * (x + 0.044715 * x * x * x)))
    y = x * cdf
    tl.store(out_ptr + offs, y.to(tl.float32), mask=mask)


def fused_layer_norm(x, weight, bias, eps=1e-5):
    orig_shape = x.shape
    x_2d = x.reshape(-1, orig_shape[-1])
    M, N = x_2d.shape
    out = torch.empty_like(x_2d)
    grid = (M,)
    layer_norm_kernel[grid](
        x_2d, weight, bias, out,
        M, N, eps,
        x_2d.stride(0),
    )
    return out.reshape(orig_shape)


def fused_softmax(x, dim=-1):
    assert dim == -1 or dim == x.dim() - 1
    orig_shape = x.shape
    x_2d = x.reshape(-1, orig_shape[-1])
    M, N = x_2d.shape
    out = torch.empty_like(x_2d)
    grid = (M,)
    softmax_kernel[grid](
        out, x_2d,
        M, N,
        x_2d.stride(0),
    )
    return out.reshape(orig_shape)


def fused_gelu(x):
    out = torch.empty_like(x)
    N = x.numel()
    grid = lambda meta: (triton.cdiv(N, meta['BLOCK_SIZE']),)
    gelu_kernel[grid](out, x, N)
    return out


# ---- Swin Transformer V2 components ----

def window_partition(x, window_size):
    B, H, W, C = x.shape
    x = x.view(B, H // window_size, window_size, W // window_size, window_size, C)
    windows = x.permute(0, 1, 3, 2, 4, 5).contiguous().view(-1, window_size, window_size, C)
    return windows


def window_reverse(windows, window_size, H, W):
    B = int(windows.shape[0] / (H * W / window_size / window_size))
    x = windows.view(B, H // window_size, W // window_size, window_size, window_size, -1)
    x = x.permute(0, 1, 3, 2, 4, 5).contiguous().view(B, H, W, -1)
    return x


def swin_window_attention(
    qkv_weight, q_bias, v_bias,
    proj_weight, proj_bias,
    logit_scale,
    cpb_mlp_0_weight, cpb_mlp_0_bias,
    cpb_mlp_2_weight,
    relative_coords_table,
    relative_position_index,
    attn_mask,
    num_heads,
    window_size=7,
):
    B_, N, C = x_windows.shape
    head_dim = C // num_heads

    # Build qkv bias
    qkv_bias = torch.cat([
        q_bias,
        torch.zeros_like(v_bias),
    ])

    # QKV projection
    qkv = torch.nn.functional.linear(x_windows, qkv_weight, qkv_bias)
    qkv = qkv.reshape(B_, N, 3, num_heads, head_dim).permute(2, 0, 1, 3, 4)
    # Wait, reshape should be (B_, N, 3, num_heads, head_dim)
    # permute to (3, B_, num_heads, N, head_dim)
    qkv = x_windows @ qkv_weight.T + qkv_bias
    qkv = qkv.reshape(B_, N, 3, num_heads, head_dim).permute(2, 0, 3, 1, 4)
    q, k, v = qkv.unbind(0)

    # Cosine attention
    q_norm = torch.nn.functional.normalize(q, dim=-1)
    k_norm = torch.nn.functional.normalize(k, dim=-1)

    # logit scale
    scale = torch.clamp(logit_scale, max=torch.log(torch.tensor(1.0 / 0.01, device=logit_scale.device))).exp()
    attn = (q_norm @ k_norm.transpose(-2, -1)) * scale

    # Relative position bias via MLP
    rel_pos = torch.nn.functional.linear(relative_coords_table.view(-1, 2), cpb_mlp_0_weight, cpb_mlp_0_bias)
    rel_pos = torch.nn.functional.relu(rel_pos)
    rel_pos = torch.nn.functional.linear(rel_pos, cpb_mlp_2_weight)
    rel_pos = rel_pos.view(relative_coords_table.shape[1], relative_coords_table.shape[2], -1)
    rel_pos = rel_pos.view(-1, num_heads)

    idx = relative_position_index.view(-1)
    rel_pos_bias = rel_pos[idx].view(window_size * window_size, window_size * window_size, num_heads)
    rel_pos_bias = rel_pos_bias.permute(2, 0, 1).contiguous()
    rel_pos_bias = torch.sigmoid(rel_pos_bias) * 16
    attn = attn + rel_pos_bias.unsqueeze(0)

    if attn_mask is not None:
        nW = attn_mask.shape[0]
        attn = attn.view(B_ // nW, nW, num_heads, N, N) + attn_mask.unsqueeze(1).unsqueeze(0)
        attn = attn.view(-1, num_heads, N, N)

    attn = fused_softmax(attn)
    # In inference, dropout is identity
    x = (attn @ v).transpose(1, 2).reshape(B_, N, C)
    x = torch.nn.functional.linear(x, proj_weight, proj_bias)
    return x


def swin_block(
    norm1_weight, norm1_bias,
    qkv_weight, q_bias, v_bias,
    proj_weight, proj_bias,
    logit_scale,
    cpb_mlp_0_weight, cpb_mlp_0_bias,
    cpb_mlp_2_weight,
    relative_coords_table,
    relative_position_index,
    attn_mask,
    norm2_weight, norm2_bias,
    mlp_fc1_weight, mlp_fc1_bias,
    mlp_fc2_weight, mlp_fc2_bias,
    num_heads,
    window_size=7,
    shift_size=0,
    H=56, W=56,
):
    B, L, C = x.shape
    shortcut = x

    # Norm1
    x_norm = fused_layer_norm(x, norm1_weight, norm1_bias)
    x_norm = x_norm.view(B, H, W, C)

    # Cyclic shift
    if shift_size > 0:
        x_norm = torch.roll(x_norm, shifts=(-shift_size, -shift_size), dims=(1, 2))

    # Window partition
    x_windows = window_partition(x_norm, window_size)
    x_windows = x_windows.view(-1, window_size * window_size, C)

    # Attention
    attn_out = swin_window_attention(
        x_windows, qkv_weight, q_bias, v_bias,
        proj_weight, proj_bias,
        logit_scale,
        cpb_mlp_0_weight, cpb_mlp_0_bias, cpb_mlp_2_weight,
        relative_coords_table, relative_position_index,
        attn_mask,
        num_heads, window_size,
    )

    # Reverse window
    attn_out = attn_out.view(-1, window_size, window_size, C)
    x_out = window_reverse(attn_out, window_size, H, W)

    if shift_size > 0:
        x_out = torch.roll(x_out, shifts=(shift_size, shift_size), dims=(1, 2))

    x_out = x_out.view(B, H * W, C)
    x = shortcut + x_out

    # MLP
    x_norm2 = fused_layer_norm(x, norm2_weight, norm2_bias)
    x_mlp = torch.nn.functional.linear(x_norm2, mlp_fc1_weight, mlp_fc1_bias)
    x_mlp = fused_gelu(x_mlp)
    x_mlp = torch.nn.functional.linear(x_mlp, mlp_fc2_weight, mlp_fc2_bias)
    x = x + x_mlp

    return x


def patch_merging(x, H, W, reduction_weight, norm_weight, norm_bias):
    B, L, C = x.shape
    x = x.view(B, H, W, C)

    x0 = x[:, 0::2, 0::2, :]
    x1 = x[:, 1::2, 0::2, :]
    x2 = x[:, 0::2, 1::2, :]
    x3 = x[:, 1::2, 1::2, :]
    x = torch.cat([x0, x1, x2, x3], dim=-1)
    x = x.view(B, -1, 4 * C)

    x = torch.nn.functional.linear(x, reduction_weight)
    x = fused_layer_norm(x, norm_weight, norm_bias)
    return x


