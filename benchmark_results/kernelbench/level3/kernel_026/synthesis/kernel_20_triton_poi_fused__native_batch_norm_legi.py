@triton.autotune(
    configs=[
        triton.Config({'BLOCK_SIZE': 1024}, num_warps=4),
        triton.Config({'BLOCK_SIZE': 2048}, num_warps=8),
        triton.Config({'BLOCK_SIZE': 512}, num_warps=4),
        triton.Config({'BLOCK_SIZE': 256}, num_warps=4),
    ],
    key=['numel'],
)
@triton.jit
def channel_shuffle_kernel(
    x_ptr, out_ptr,
    N, C, H, W,
    groups,
    numel,
    BLOCK_SIZE: tl.constexpr,
):
    pid = tl.program_id(0)
    offsets = pid * BLOCK_SIZE + tl.arange(0, BLOCK_SIZE)
    mask = offsets < numel

    # offsets index into output tensor (N, C, H, W) in NCHW layout
    # output[n, c, h, w] = input[n, c_shuffled, h, w]
    # Channel shuffle: input shape (N, groups, C//groups, H, W)
    # output[n, c_per_group, group, h, w] = input[n, group, c_per_group, h, w]
    # i.e., output channel c = (c % groups) * (C//groups) + (c // groups)
    # which means: if output index is c, then input channel is (c % groups) * (C//groups) + (c // groups)

    w_idx = offsets % W
    tmp = offsets // W
    h_idx = tmp % H
    tmp = tmp // H
    c_idx = tmp % C
    n_idx = tmp // C

    channels_per_group = C // groups
    # input channel for this output channel
    in_c = (c_idx % channels_per_group) * groups + (c_idx // channels_per_group)

    in_offsets = n_idx * C * H * W + in_c * H * W + h_idx * W + w_idx
    val = tl.load(x_ptr + in_offsets, mask=mask, other=0.0)
    tl.store(out_ptr + offsets, val, mask=mask)


