# ShuffleNet unit
# ============================================================

def shufflenet_unit(x, conv1_w, bn1_w, bn1_b, bn1_rm, bn1_rv,
                    conv2_w, bn2_w, bn2_b, bn2_rm, bn2_rv,
                    conv3_w, bn3_w, bn3_b, bn3_rm, bn3_rv,
                    shortcut_conv_w=None, shortcut_bn_w=None, shortcut_bn_b=None,
                    shortcut_bn_rm=None, shortcut_bn_rv=None,
                    groups=3, eps=1e-5):
    # conv1: 1x1 group conv
    out = do_conv2d(x, conv1_w, stride=1, padding=0, groups=groups)
    out = do_bn_relu(out, bn1_w, bn1_b, bn1_rm, bn1_rv, eps)
    
    # conv2: depthwise 3x3
    mid_c = out.shape[1]
    out = do_conv2d(out, conv2_w, stride=1, padding=1, groups=mid_c)
    out = do_bn(out, bn2_w, bn2_b, bn2_rm, bn2_rv, eps)
    
    # channel shuffle
    out = do_channel_shuffle(out, groups)
    
    # conv3: 1x1 group conv
    out = do_conv2d(out, conv3_w, stride=1, padding=0, groups=groups)
    
    # shortcut
    if shortcut_conv_w is not None:
        sc = do_conv2d(x, shortcut_conv_w, stride=1, padding=0)
        sc = do_bn(sc, shortcut_bn_w, shortcut_bn_b, shortcut_bn_rm, shortcut_bn_rv, eps)
        out = do_bn_add(out, sc, bn3_w, bn3_b, bn3_rm, bn3_rv, eps)
    else:
        out = do_bn_add(out, x, bn3_w, bn3_b, bn3_rm, bn3_rv, eps)
    
    return out


