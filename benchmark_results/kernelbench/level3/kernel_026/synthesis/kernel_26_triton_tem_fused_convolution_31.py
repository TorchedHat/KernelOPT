# Fused BatchNorm + ReLU Triton kernel
@triton.autotune(
    configs=[
        triton.Config({'BLOCK_SIZE': 1024}, num_warps=4),
        triton.Config({'BLOCK_SIZE': 2048}, num_warps=8),
        triton.Config({'BLOCK_SIZE': 512}, num_warps=4),
        triton.Config({'BLOCK_SIZE': 256}, num_warps=2),
    ],
    key=['numel', 'C'],
)
@triton.jit
def fused_bn_relu_kernel(
    x_ptr, mean_ptr, var_ptr, weight_ptr, bias_ptr,
    out_ptr,
    numel, C,
    eps,
    BLOCK_SIZE: tl.constexpr,
):
    pid = tl.program_id(0)
    offsets = pid * BLOCK_SIZE + tl.arange(0, BLOCK_SIZE)
    mask = offsets < numel
    
    x = tl.load(x_ptr + offsets, mask=mask, other=0.0)
    
    # Channel index: layout is (N, C, H, W) so channel = (offset // (H*W)) % C
    # But we pass C and spatial size separately
    # Actually we need channel index from flat index
    # numel = N * C * H * W, channel stride = H*W
    # channel = (offset // spatial) % C where spatial = numel // (N*C) ... 
    # We'll compute channel from offset % (C * spatial) // spatial
    # Pass spatial as parameter
    c_idx = (offsets // (numel // C)) % C  # This won't work generally
    # Better: pass spatial_size = H*W
    # Let's restructure - we need channel index
    # offset = n * C * S + c * S + s where S = H*W
    # c = (offset // S) % C
    # We need S = numel / (N*C) but we don't have N here
    # Let's just pass C and compute: c = (offset % (C * S)) // S
    # Actually simplest: pass stride_c = S
    c_idx2 = (offsets // (numel // C)) % C
    
    mean = tl.load(mean_ptr + c_idx2, mask=mask, other=0.0)
    var = tl.load(var_ptr + c_idx2, mask=mask, other=0.0)
    weight = tl.load(weight_ptr + c_idx2, mask=mask, other=1.0)
    bias = tl.load(bias_ptr + c_idx2, mask=mask, other=0.0)
    
    x_norm = (x - mean) / tl.sqrt(var + eps)
    out = x_norm * weight + bias
    out = tl.maximum(out, 0.0)
    
    tl.store(out_ptr + offsets, out, mask=mask)


