"""Assemble optimized Triton kernels into a single clean output file.

Takes the best kernel files from optimization and produces one
self-contained .py file with:
  - Module docstring describing the original model
  - All imports
  - All @triton.jit kernel definitions
  - kernel_function(*inputs) wrapper
  - get_inputs() for benchmarking
  - __main__ block for profiling
"""
from __future__ import annotations

import re
from pathlib import Path


def assemble_output(
    generated_kernels: list[dict],
    optimized_dir: Path,
    original_pytorch_path: str,
    model_description: str = "",
) -> str:
    """Assemble optimized kernels into a single clean output file.

    Args:
        generated_kernels: List of dicts with kernel_name, source, path.
        optimized_dir: Directory containing opt_*/best_kernel.py files.
        original_pytorch_path: Path to original KernelBench .py file.
        model_description: Human-readable description of the model.

    Returns:
        Complete Python source for the final output file.
    """
    # Collect best kernel sources
    kernel_sources = []
    for gk in generated_kernels:
        best_path = optimized_dir / f"opt_{gk['kernel_name'][:60]}" / "best_kernel.py"
        if best_path.exists():
            kernel_sources.append(best_path.read_text())
        else:
            kernel_sources.append(gk["source"])

    if len(kernel_sources) == 1:
        return _assemble_single(kernel_sources[0], original_pytorch_path, model_description)

    return _assemble_multi(kernel_sources, generated_kernels, original_pytorch_path, model_description)


def _assemble_single(
    kernel_source: str,
    original_pytorch_path: str,
    model_description: str,
) -> str:
    """For a single kernel, clean up the source and add a docstring."""
    lines = kernel_source.strip().split("\n")

    # Find where imports end and kernel starts
    import_end = 0
    for i, line in enumerate(lines):
        if line.strip().startswith(("import ", "from ")):
            import_end = i + 1

    # Build docstring from model description or original file
    if not model_description:
        try:
            orig = Path(original_pytorch_path).read_text()
            doc_match = re.search(r'"""(.*?)"""', orig, re.DOTALL)
            if doc_match:
                model_description = doc_match.group(1).strip()
        except OSError:
            pass

    docstring = ""
    if model_description:
        docstring = f'"""\n{model_description}\n\nOptimized Triton kernel generated by KernelOpt.\n"""\n\n'

    # Deduplicate imports
    imports = set()
    other_lines = []
    for line in lines:
        stripped = line.strip()
        if stripped.startswith(("import ", "from ")) and "argparse" not in stripped:
            imports.add(stripped)
        else:
            other_lines.append(line)

    sorted_imports = sorted(imports)
    body = "\n".join(other_lines).strip()

    return docstring + "\n".join(sorted_imports) + "\n\n\n" + body + "\n"


def _assemble_multi(
    kernel_sources: list[str],
    generated_kernels: list[dict],
    original_pytorch_path: str,
    model_description: str,
) -> str:
    """For multiple kernels, combine into one file with shared imports."""
    all_imports = set()
    kernel_bodies = []

    for src, gk in zip(kernel_sources, generated_kernels):
        lines = src.strip().split("\n")

        body_lines = []
        in_main = False
        for line in lines:
            stripped = line.strip()
            if stripped.startswith(("import ", "from ")) and "argparse" not in stripped:
                all_imports.add(stripped)
            elif stripped.startswith("if __name__"):
                in_main = True
            elif not in_main:
                body_lines.append(line)

        body = "\n".join(body_lines).strip()
        if body:
            kernel_bodies.append(f"# --- {gk['kernel_name']} ---\n{body}")

    if not model_description:
        try:
            orig = Path(original_pytorch_path).read_text()
            doc_match = re.search(r'"""(.*?)"""', orig, re.DOTALL)
            if doc_match:
                model_description = doc_match.group(1).strip()
        except OSError:
            pass

    docstring = ""
    if model_description:
        docstring = f'"""\n{model_description}\n\nOptimized Triton kernels generated by KernelOpt.\n"""\n\n'

    sorted_imports = sorted(all_imports)

    main_block = (
        '\n\nif __name__ == "__main__":\n'
        '    import argparse\n'
        '    parser = argparse.ArgumentParser()\n'
        '    parser.add_argument("--profile-only", action="store_true")\n'
        '    args = parser.parse_args()\n'
        '    inputs = get_inputs()\n'
        '    output = kernel_function(*inputs)\n'
        '    torch.cuda.synchronize()\n'
        '    if not args.profile_only:\n'
        '        print("Kernel executed successfully.")\n'
    )

    return (
        docstring
        + "\n".join(sorted_imports) + "\n\n\n"
        + "\n\n\n".join(kernel_bodies) + "\n"
        + main_block
    )
